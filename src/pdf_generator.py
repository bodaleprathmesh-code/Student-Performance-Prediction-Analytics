from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer
)
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.colors import darkblue
from reportlab.lib.units import inch

import io
from datetime import datetime


def generate_pdf(student_data,
                 predicted_marks,
                 performance,
                 risk,
                 recommendations):

    buffer = io.BytesIO()

    doc = SimpleDocTemplate(buffer)

    styles = getSampleStyleSheet()

    title = styles["Heading1"]
    title.alignment = TA_CENTER
    title.textColor = darkblue

    heading = styles["Heading2"]
    normal = styles["BodyText"]

    story = []

    story.append(
        Paragraph(
            "Student Performance Prediction Report",
            title
        )
    )

    story.append(Spacer(1, 0.25 * inch))

    story.append(
        Paragraph(
            f"<b>Date :</b> {datetime.now().strftime('%d-%m-%Y %H:%M')}",
            normal
        )
    )

    story.append(Spacer(1, 0.2 * inch))

    story.append(
        Paragraph(
            "Student Information",
            heading
        )
    )

    story.append(Spacer(1, 0.1 * inch))

    for col in student_data.columns:

        value = student_data.iloc[0][col]

        story.append(
            Paragraph(
                f"<b>{col}</b> : {value}",
                normal
            )
        )

    story.append(Spacer(1, 0.25 * inch))

    story.append(
        Paragraph(
            "Prediction Result",
            heading
        )
    )

    story.append(
        Paragraph(
            f"<b>Predicted Marks :</b> {predicted_marks:.2f}",
            normal
        )
    )

    story.append(
        Paragraph(
            f"<b>Performance :</b> {performance}",
            normal
        )
    )

    story.append(
        Paragraph(
            f"<b>Risk Level :</b> {risk}",
            normal
        )
    )

    story.append(Spacer(1, 0.25 * inch))

    story.append(
        Paragraph(
            "Recommendations",
            heading
        )
    )

    for rec in recommendations:

        story.append(
            Paragraph(
                "• " + rec,
                normal
            )
        )

    story.append(Spacer(1, 0.3 * inch))

    story.append(
        Paragraph(
            "<i>Generated by Student Performance Prediction System</i>",
            normal
        )
    )

    doc.build(story)

    pdf = buffer.getvalue()

    buffer.close()

    return pdf